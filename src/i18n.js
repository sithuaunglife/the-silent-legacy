const reverse=new Map(Object.entries(MY).map(([english,my])=>[my,english]));
export function translate(lang,english){
  return lang==='my' ? MY[english] || english : reverse.get(english) || english;
}
const original=new WeakMap();
const rendered=new WeakMap();
function translateNode(node,lang){
  if(node.nodeType!==Node.TEXT_NODE)return;
  const raw=node.nodeValue;
  if(!raw || !raw.trim())return;
  let english=original.get(node);
  if(english===undefined || rendered.get(node)!==raw){
    english=reverse.get(raw.trim()) || raw.trim();
    original.set(node,english);
  }
  const out=translate(lang,english);
  const next=raw.replace(raw.trim(),out);
  rendered.set(node,next);
  if(raw!==next)node.nodeValue=next;
}
function translateTree(root,lang){
  if(!root)return;
  if(root.nodeType===Node.TEXT_NODE){translateNode(root,lang);return;}
  if(root.nodeType!==Node.ELEMENT_NODE && root.nodeType!==Node.DOCUMENT_NODE)return;
  if(root.nodeType===Node.ELEMENT_NODE && root.closest?.('[data-i18n-ignore],script,style,textarea'))return;
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  const nodes=[];
  while(walker.nextNode())nodes.push(walker.currentNode);
  // Keep branded/title-screen copy in English even when Myanmar UI is selected.
  // The observer starts at document.body, so check every text node's ancestors.
  for(const node of nodes){
    if(node.parentElement?.closest('[data-i18n-ignore]'))continue;
    translateNode(node,lang);
  }
}
export function localizeInterface(language){
  let scheduled=false;
  const run=()=>{scheduled=false;translateTree(document.body,language)};
  run();
  const observer=new MutationObserver(()=>{
    if(scheduled)return;
    scheduled=true;
    queueMicrotask(run);
  });
  observer.observe(document.body,{childList:true,characterData:true,subtree:true});
  return()=>observer.disconnect();
}
